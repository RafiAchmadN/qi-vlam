"""URDF generator for ROS / Gazebo / Isaac / PyBullet users.

Same kinematic chain as `src/sim/mjcf.py` and `src/robot/arm.py` (tested:
the `tip_link` pose from this URDF == `arm.fk`). Joint names match the app
and the bridge (`arm.JOINT_NAMES`), so `/joint_states` published by any ROS
driver or by `ros2/qi_vla_ros` can be consumed by the app over rosbridge.

The gripper joint carries the app's normalized value (0 closed .. 1 open)
as a massless revolute "virtual" joint; the two prismatic fingers mimic it
with multiplier FINGER_OPEN (metres), so robot_state_publisher shows real
finger motion.

    python -m src.sim.urdf --out ros2/qi_vla_ros/urdf/qi_vla_arm.urdf
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict

import numpy as np

from src.robot import arm
from src.sim.mjcf import FINGER_OPEN


def _inertial(m: float, r: float = 0.02) -> str:
    i = 0.4 * m * r * r
    return (f'<inertial><mass value="{m}"/><inertia ixx="{i:.3e}" iyy="{i:.3e}" izz="{i:.3e}" '
            f'ixy="0" ixz="0" iyz="0"/></inertial>')


def _cyl(length: float, radius: float, color: str) -> str:
    g = f'<geometry><cylinder length="{length}" radius="{radius}"/></geometry>'
    o = f'<origin xyz="0 0 {length / 2}" rpy="0 0 0"/>'
    return (f'<visual>{o}{g}<material name="{color}"/></visual>'
            f'<collision>{o}{g}</collision>')


def build_urdf() -> str:
    H0, L1, L2, L3 = arm.LINKS
    lo, hi, vmax = arm.Q_MIN, arm.Q_MAX, arm.QD_MAX
    effort = [2.5, 3.5, 2.5, 1.5, 1.0]
    rev = lambda name, parent, child, xyz, axis, k: (  # noqa: E731
        f'<joint name="{name}" type="revolute"><parent link="{parent}"/><child link="{child}"/>'
        f'<origin xyz="{xyz}" rpy="0 0 0"/><axis xyz="{axis}"/>'
        f'<limit lower="{lo[k]}" upper="{hi[k]}" velocity="{vmax[k]}" effort="{effort[k]}"/></joint>')
    finger = lambda side, sign: (  # noqa: E731
        f'<link name="finger_{side}">{_inertial(0.01, 0.01)}'
        f'<visual><origin xyz="0 {sign * 0.004} 0"/><geometry><box size="0.018 0.008 0.052"/></geometry>'
        f'<material name="dark"/></visual>'
        f'<collision><origin xyz="0 {sign * 0.004} 0"/><geometry><box size="0.018 0.008 0.052"/></geometry></collision></link>'
        f'<joint name="finger_{side}_joint" type="prismatic"><parent link="hand"/><child link="finger_{side}"/>'
        f'<origin xyz="0 0 {L3 - 0.016}"/><axis xyz="0 {sign} 0"/>'
        f'<limit lower="0" upper="{FINGER_OPEN}" velocity="0.1" effort="4"/>'
        f'<mimic joint="gripper" multiplier="{FINGER_OPEN}" offset="0"/></joint>')
    xml = f"""<?xml version="1.0"?>
<!-- Generated by src/sim/urdf.py from src/robot/arm.py — do not edit by hand. -->
<robot name="qi_vla_arm">
  <material name="dark"><color rgba="0.22 0.28 0.31 1"/></material>
  <material name="light"><color rgba="0.69 0.75 0.77 1"/></material>
  <link name="base_link">{_inertial(0.3, 0.05)}{_cyl(0.03, 0.05, "dark")}</link>
  <link name="pan_link">{_inertial(0.12)}{_cyl(H0, 0.022, "dark")}</link>
  <link name="upper_arm">{_inertial(0.10)}{_cyl(L1, 0.018, "light")}</link>
  <link name="forearm">{_inertial(0.08)}{_cyl(L2, 0.015, "light")}</link>
  <link name="wrist">{_inertial(0.03)}{_cyl(L3 - 0.05, 0.012, "light")}</link>
  <link name="hand">{_inertial(0.03)}<visual><origin xyz="0 0 {L3 - 0.042}"/><geometry><box size="0.024 0.06 0.012"/></geometry><material name="dark"/></visual></link>
  <link name="gripper_link">{_inertial(0.001, 0.001)}</link>
  <link name="tip_link"/>
  {rev("shoulder_pan", "base_link", "pan_link", "0 0 0", "0 0 1", 0)}
  {rev("shoulder_lift", "pan_link", "upper_arm", f"0 0 {H0}", "0 1 0", 1)}
  {rev("elbow_flex", "upper_arm", "forearm", f"0 0 {L1}", "0 1 0", 2)}
  {rev("wrist_flex", "forearm", "wrist", f"0 0 {L2}", "0 1 0", 3)}
  {rev("wrist_roll", "wrist", "hand", "0 0 0", "0 0 1", 4)}
  <joint name="gripper" type="revolute"><parent link="hand"/><child link="gripper_link"/>
    <origin xyz="0 0 {L3 - 0.03}"/><axis xyz="0 0 1"/><limit lower="0" upper="1" velocity="2" effort="1"/></joint>
  <joint name="tip_joint" type="fixed"><parent link="hand"/><child link="tip_link"/><origin xyz="0 0 {L3}"/></joint>
  {finger("l", 1)}
  {finger("r", -1)}
</robot>
"""
    return xml


def build_rover_urdf() -> str:
    """Diff-drive rover (src/sim/mobile, app/public/maps/index.json robot spec):
    base_footprint -> base_link -> wheels (continuous) + base_scan (lidar)."""
    import json
    from src.sim.mobile.geometry import robot_spec
    R = robot_spec()
    rw, bt, rad, lh = R["wheel_radius"], R["half_track"], R["radius"], R["lidar"]["height"]
    wheel = lambda side, y: (  # noqa: E731
        f'<link name="wheel_{side}_link">{_inertial(0.05, rw)}<visual><origin rpy="1.5708 0 0"/>'
        f'<geometry><cylinder radius="{rw}" length="0.018"/></geometry><material name="dark"/></visual>'
        f'<collision><origin rpy="1.5708 0 0"/><geometry><cylinder radius="{rw}" length="0.018"/></geometry></collision></link>'
        f'<joint name="wheel_{side}_joint" type="continuous"><parent link="base_link"/><child link="wheel_{side}_link"/>'
        f'<origin xyz="0 {y} 0"/><axis xyz="0 1 0"/></joint>')
    return f"""<?xml version="1.0"?>
<!-- Generated by src/sim/urdf.py (build_rover_urdf) from app/public/maps/index.json — do not edit by hand. -->
<robot name="qi_vla_rover">
  <material name="dark"><color rgba="0.22 0.28 0.31 1"/></material>
  <material name="black"><color rgba="0.1 0.1 0.12 1"/></material>
  <link name="base_footprint"/>
  <link name="base_link">{_inertial(0.8, rad)}
    <visual><origin xyz="0 0 0.012"/><geometry><cylinder radius="{rad}" length="0.07"/></geometry><material name="dark"/></visual>
    <collision><origin xyz="0 0 0.012"/><geometry><cylinder radius="{rad}" length="0.07"/></geometry></collision></link>
  <joint name="base_joint" type="fixed"><parent link="base_footprint"/><child link="base_link"/><origin xyz="0 0 {rw}"/></joint>
  {wheel("left", bt)}
  {wheel("right", -bt)}
  <link name="base_scan">{_inertial(0.1, 0.035)}<visual><geometry><cylinder radius="0.035" length="0.04"/></geometry><material name="black"/></visual></link>
  <joint name="scan_joint" type="fixed"><parent link="base_link"/><child link="base_scan"/><origin xyz="0 0 {lh - rw}"/></joint>
</robot>
"""


def _rot(axis, a):
    axis = np.asarray(axis, dtype=float)
    axis = axis / np.linalg.norm(axis)
    K = np.array([[0, -axis[2], axis[1]], [axis[2], 0, -axis[0]], [-axis[1], axis[0], 0]])
    return np.eye(3) + np.sin(a) * K + (1 - np.cos(a)) * K @ K


def urdf_fk(xml: str, q: Dict[str, float], link: str = "tip_link") -> np.ndarray:
    """Minimal URDF forward kinematics (revolute/fixed, rpy=0) — for tests."""
    root = ET.fromstring(xml)
    by_child = {j.find("child").get("link"): j for j in root.findall("joint")}
    chain = []
    cur = link
    while cur in by_child:
        j = by_child[cur]
        chain.append(j)
        cur = j.find("parent").get("link")
    R, p = np.eye(3), np.zeros(3)
    for j in reversed(chain):
        o = np.array([float(v) for v in j.find("origin").get("xyz").split()])
        p = p + R @ o
        if j.get("type") == "revolute":
            R = R @ _rot([float(v) for v in j.find("axis").get("xyz").split()], q.get(j.get("name"), 0.0))
    return p


def main() -> None:
    a = argparse.ArgumentParser()
    a.add_argument("--out", default="ros2/qi_vla_ros/urdf/qi_vla_arm.urdf")
    a.add_argument("--rover-out", default="ros2/qi_vla_ros/urdf/qi_vla_rover.urdf")
    args = a.parse_args()
    for path, xml in ((args.out, build_urdf()), (args.rover_out, build_rover_urdf())):
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(xml, encoding="utf-8")
        print(out)


if __name__ == "__main__":
    main()
